"""src/figures/fig_s3.py: the table number format and the figure registry (Figs. 4-5 and Tables
II-III are generated by `make figures`; Figs. 1-3 are final, without "preliminary")."""
from __future__ import annotations

import numpy as np

from src.figures import fig_c, fig_s3, make_all


def test_sci_format():
    assert fig_s3._sci(1.234e-3) == r"$1.2\times10^{-3}$"
    assert fig_s3._sci(9.96e-5) == r"$1.0\times10^{-4}$"          # rounding carries the exponent
    assert fig_s3._sci(0.0) == "$0$" and fig_s3._sci(np.nan) == "--" and fig_s3._sci(None) == "--"
    assert fig_s3._sci(-2.5e2, nd=3) == r"$-2.50\times10^{2}$"


def test_registry_and_final_names():
    names = [n for n, _ in make_all.FIGURES]
    assert names[:4] == ["fig1_cost_curves", "fig2_alignment", "fig3_attribution", "fig_c3_summary"]
    assert names[4:] == ["fig4_value_functions", "fig5_formulations", "table2_i1", "table3_n2"]
    assert fig_c.TAG == ""
