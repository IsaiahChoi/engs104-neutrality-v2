"""`make figures`: every figure and report/numbers.tex (CLAUDE.md rule 8; DESIGN §10).

numbers.tex holds every number the report uses as a LaTeX macro, each preceded by a comment
naming its source file and that file's sha256 (CHECKS K32). Output is deterministic: no
timestamps, fixed order, so regeneration is byte-identical (K33). In S1 it holds the design
constants read from the configs; result macros and the figure functions (FIGURES) are added as
the experiments produce their outputs (S2 onward).
"""
from __future__ import annotations

import hashlib
import math
import sys
from pathlib import Path

import yaml

from src.figures.fig_c import FIGURES as C_FIGURES
from src.figures.fig_s3 import FIGURES as S3_FIGURES
from src.figures.numbers import result_macros, table1_mandate, table3_n2b, table_experiments
from src.utils import ROOT

NUMBERS = ROOT / "report" / "numbers.tex"
BASE_MANDATE = "experiments/configs/base_mandate.yaml"
INSTANCES = "experiments/instances.py"
FIGURES: list = [*C_FIGURES, *S3_FIGURES]   # (name, function) pairs: Figs. 1-3 and the C3 summary (S2);
                                             # Figs. 4-5 and Tables II-III (S3)
REPORT_TABLES: list = [("table1_mandate", table1_mandate),   # Table I, from the configs (S4)
                       ("table_experiments", table_experiments), ("table3_n2b", table3_n2b)]   # S4b


def sha256(rel: str) -> str:
    return hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()


def _num(x: float) -> str:
    """Plain decimal for LaTeX: rounded to 10 significant digits (so 100·0.07 prints 7), never in
    exponent notation, no trailing zeros: 2.0 -> '2', 0.05 -> '0.05'."""
    v = float(f"{float(x):.10g}")
    s = f"{v:.12f}".rstrip("0").rstrip(".")
    if float(s) != v:
        raise ValueError(f"{x} needs more than 12 decimals")
    return s


def _fixed(x: float, nd: int) -> str:
    """x with exactly nd decimals; refuses a value that the rounding would change."""
    s = f"{float(x):.{nd}f}"
    if not math.isclose(float(s), float(x), rel_tol=0, abs_tol=1e-12):
        raise ValueError(f"{x} does not have {nd} decimals")
    return s


def _pow10(x: float) -> str:
    """'\\ensuremath{10^{k}}' for x = 10^k (usable in text and math mode)."""
    k = round(math.log10(x))
    if not math.isclose(x, 10.0**k, rel_tol=1e-12):
        raise ValueError(f"{x} is not a power of ten")
    return f"\\ensuremath{{10^{{{k}}}}}"


def design_constants() -> list[tuple[str, str, str]]:
    """(macro name, value, source file) for the design constants."""
    cfg = yaml.safe_load((ROOT / BASE_MANDATE).read_text())
    m, rb = cfg["mandate"], cfg["risk_budget"]
    from experiments.instances import MIQP_POSITION_CAP
    return [
        ("RiskBudgetPct", _num(100 * rb["target_annual_vol"]), BASE_MANDATE),
        ("LambdaMin", _pow10(rb["lambda_min"]), BASE_MANDATE),
        ("RootRtol", _pow10(rb["root_rtol"]), BASE_MANDATE),
        ("BaseGross", _num(m["gross"]), BASE_MANDATE),
        ("BaseNetPct", _num(100 * m["dollar"]), BASE_MANDATE),
        ("BaseBeta", _fixed(m["beta"], 2), BASE_MANDATE),
        ("BaseStyle", _fixed(m["style"], 2), BASE_MANDATE),
        ("BaseSectorPct", _num(100 * m["sector"]), BASE_MANDATE),
        ("BasePositionPct", _num(100 * m["position"]), BASE_MANDATE),
        ("BaseLiquidityPct", _num(100 * m["liquidity_theta"]), BASE_MANDATE),
        ("AUMBillion", _num(m["aum_usd"] / 1e9), BASE_MANDATE),
        ("BorrowBpYear", _num(1e4 * m["borrow_annual"]), BASE_MANDATE),
        ("TradeCostBp", _num(1e4 * m["trade_cost"]), BASE_MANDATE),
        ("MiqpPositionPct", _num(100 * MIQP_POSITION_CAP), INSTANCES),
    ]


def write_numbers(path: Path = NUMBERS) -> Path:
    rows = design_constants() + result_macros()        # result macros: src/figures/numbers.py (S4)
    names = [r[0] for r in rows]
    if len(set(names)) != len(names):
        raise ValueError("duplicate macro names")
    lines = ["% numbers.tex: generated by `make figures` (src/figures/make_all.py). Do not edit.",
             "% Each macro is preceded by its source file and that file's sha256.", ""]
    for name, value, src in rows:
        lines += [f"% source: {src} sha256={sha256(src)}", f"\\newcommand{{\\{name}}}{{{value}}}"]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path


def main() -> int:
    for name, fn in FIGURES + REPORT_TABLES:
        fn()
        print(f"figure {name}", flush=True)
    print(f"wrote {write_numbers().relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
